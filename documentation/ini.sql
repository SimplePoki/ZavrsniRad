BEGIN;
DROP TABLE IF EXISTS evidencije CASCADE;
DROP TABLE IF EXISTS akcije CASCADE;
DROP TABLE IF EXISTS tip_evidencije CASCADE;
DROP TABLE IF EXISTS smjene CASCADE;
DROP TABLE IF EXISTS posjeti CASCADE;
DROP TABLE IF EXISTS umirovljenik CASCADE;
DROP TABLE IF EXISTS lokacije CASCADE;
DROP TABLE IF EXISTS korisnik CASCADE;


CREATE TABLE IF NOT EXISTS korisnik (
	id serial NOT NULL,
	ime varchar(255) NOT NULL,
	prezime varchar(255) NOT NULL,
	lozinka varchar(255) NOT NULL,
	email varchar(255) NOT NULL UNIQUE,
	uloga integer NOT NULL,
	aktivan boolean NOT NULL DEFAULT true,
	created_at timestamp with time zone NOT NULL DEFAULT now(),
	updated_at timestamp with time zone,
	PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS lokacije (
	id serial NOT NULL,
	parent_id integer,
	naziv varchar(255) NOT NULL,
	tip integer NOT NULL,
	created_at timestamp with time zone NOT NULL DEFAULT now(),
	updated_at timestamp with time zone,
	PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS umirovljenik (
	id serial NOT NULL,
	ime varchar(255) NOT NULL,
	prezime varchar(255) NOT NULL,
	lokacija_id integer NOT NULL,
	aktivan boolean NOT NULL DEFAULT true,
	created_at timestamp with time zone NOT NULL DEFAULT now(),
	updated_at timestamp with time zone,
	PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS posjeti (
	id serial NOT NULL,
	umirovljenik_id integer NOT NULL,
	ime varchar(255) NOT NULL,
	prezime varchar(255) NOT NULL,
	datum date NOT NULL,
	upisao_id integer NOT NULL,
	created_at timestamp with time zone NOT NULL DEFAULT now(),
	updated_at timestamp with time zone,
	PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS smjene (
	id serial NOT NULL,
	korisnik_id integer NOT NULL,
	datum date NOT NULL,
	smjena integer NOT NULL,
	created_at timestamp with time zone NOT NULL DEFAULT now(),
	updated_at timestamp with time zone,
	PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS tip_evidencije (
	id integer NOT NULL,
	naziv varchar(255) NOT NULL,
	opis varchar(500) NOT NULL,
	aktivan boolean NOT NULL DEFAULT true,
	created_at timestamp with time zone NOT NULL DEFAULT now(),
	updated_at timestamp with time zone,
	PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS akcije (
	id integer NOT NULL,
	tip_id integer NOT NULL,
	naziv varchar(255) NOT NULL,
	opis varchar(500) NOT NULL,
	aktivna boolean NOT NULL DEFAULT true,
	created_at timestamp with time zone NOT NULL DEFAULT now(),
	updated_at timestamp with time zone,
	PRIMARY KEY (id, tip_id)
);
CREATE TABLE IF NOT EXISTS evidencije (
	id serial NOT NULL,
	umirovljenik_id integer,
	lokacija_id integer,
	izvrsio_id integer NOT NULL,
	akcija_tip_id integer NOT NULL,
	akcija_id integer NOT NULL,
	datum_vrijeme timestamp with time zone NOT NULL DEFAULT now(),
	vrijednost_num numeric(10,2),
	vrijednost_string varchar(255),
	vrijednost_bool boolean,
	opis text,
	created_at timestamp with time zone NOT NULL DEFAULT now(),
	updated_at timestamp with time zone,
	PRIMARY KEY (id),
	CHECK (
       umirovljenik_id IS NOT NULL
       OR lokacija_id IS NOT NULL
    ),
	CHECK (
	   vrijednost_num IS NOT NULL
	   OR vrijednost_string IS NOT NULL
	   OR vrijednost_bool IS NOT NULL
	   OR opis IS NOT NULL
	)

);
ALTER TABLE lokacije ADD CONSTRAINT lokacija_parent_fk FOREIGN KEY (parent_id) REFERENCES lokacije (id);
ALTER TABLE umirovljenik ADD CONSTRAINT umirovljenik_fk3 FOREIGN KEY (lokacija_id) REFERENCES lokacije(id);
ALTER TABLE posjeti ADD CONSTRAINT posjeti_umirovljenik_fk FOREIGN KEY (umirovljenik_id) REFERENCES umirovljenik (id);
ALTER TABLE posjeti ADD CONSTRAINT posjeti_upisao_fk FOREIGN KEY (upisao_id) REFERENCES korisnik (id);
ALTER TABLE smjene ADD CONSTRAINT smjene_korisnik_fk FOREIGN KEY (korisnik_id) REFERENCES korisnik (id);
ALTER TABLE akcije ADD CONSTRAINT akcije_tip_fk FOREIGN KEY (tip_id) REFERENCES tip_evidencije (id);
ALTER TABLE evidencije ADD CONSTRAINT evidencije_umirovljenik_fk FOREIGN KEY (umirovljenik_id) REFERENCES umirovljenik (id);
ALTER TABLE evidencije ADD CONSTRAINT evidencije_lokacija_fk FOREIGN KEY (lokacija_id) REFERENCES lokacije (id);
ALTER TABLE evidencije ADD CONSTRAINT evidencije_akcija_fk FOREIGN KEY (akcija_id, akcija_tip_id) REFERENCES akcije (id, tip_id);
ALTER TABLE evidencije ADD CONSTRAINT evidencije_izvrsio_fk FOREIGN KEY (izvrsio_id) REFERENCES korisnik (id);

CREATE OR REPLACE FUNCTION updated()
RETURNS TRIGGER AS $$
BEGIN
	IF NEW IS DISTINCT FROM OLD THEN
    	NEW.updated_at = now();
	END IF;
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER umirovljenik_updated
BEFORE UPDATE ON umirovljenik
FOR EACH ROW EXECUTE FUNCTION updated();

CREATE TRIGGER posjeti_updated
BEFORE UPDATE ON posjeti
FOR EACH ROW EXECUTE FUNCTION updated();

CREATE TRIGGER korisnik_updated
BEFORE UPDATE ON korisnik
FOR EACH ROW EXECUTE FUNCTION updated();

CREATE TRIGGER smjene_updated
BEFORE UPDATE ON smjene
FOR EACH ROW EXECUTE FUNCTION updated();

CREATE TRIGGER evidencije_updated
BEFORE UPDATE ON evidencije
FOR EACH ROW EXECUTE FUNCTION updated();

CREATE TRIGGER akcije_updated
BEFORE UPDATE ON akcije
FOR EACH ROW EXECUTE FUNCTION updated();

